/**
 * Numeric value behind a price label ("de la 400 lei" -> 400), so tariffs can
 * be sorted cheapest-first. Anything unparseable sorts last.
 */
export function priceValue(price) {
  const match = String(price ?? "").match(/\d+/);
  return match ? Number(match[0]) : Number.POSITIVE_INFINITY;
}

/** Services of one group, ordered by lowest price first. */
export function servicesByPrice(groupId) {
  return SERVICES.filter((s) => s.group === groupId).sort(
    (a, b) => priceValue(a.price) - priceValue(b.price)
  );
}
